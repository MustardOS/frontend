static const unsigned char *glyph_rows(const char character) {
    const char upper = (char) toupper((unsigned char) character);
    for (size_t index = 0; index < sizeof(glyphs) / sizeof(glyphs[0]); index++) {
        if (glyphs[index].character == upper) return glyphs[index].rows;
    }
    return NULL;
}

int pixfont_width(const char *text, const int scale) {
    if (!text || !*text) return 0;
    int count = 0;
    for (const char *cursor = text; *cursor; cursor++)
        count++;
    return (count * 6 - 1) * scale;
}

void pixfont_draw(SDL_Renderer *renderer, const char *text, const int x, const int y, const int scale) {
    if (!renderer || !text) return;
    SDL_Rect rects[35];
    int cursor_x = x;
    for (const char *cursor = text; *cursor; cursor++, cursor_x += 6 * scale) {
        const unsigned char *rows = glyph_rows(*cursor);
        if (!rows) continue;
        int count = 0;
        for (int row = 0; row < 7; row++) {
            for (int column = 0; column < 5; column++) {
                if (!(rows[row] & (0x10 >> column))) continue;
                rects[count++] = (SDL_Rect) {cursor_x + column * scale, y + row * scale, scale, scale};
            }
        }
        if (count) SDL_RenderFillRects(renderer, rects, count);
    }
}
